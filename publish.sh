#!/bin/sh
# publish.sh — publie les sources du site (docs/, à la racine du projet) sur GitHub.
#
# Le résultat du site obtenu à partir des scans est enregistré sur GitHub dans ce
# sous-répertoire `classes-prepa/` (dépôt https://github.com/francoismora/classes-prepa.git,
# servi par GitHub Pages à https://francoismora.github.io/classes-prepa/).
# Aucun fichier .jpg n'est jamais copié ni poussé.
#
# Le dépôt git effectif vit dans /tmp/classes-prepa-git (GIT_DIR externe) avec
# core.worktree = ce répertoire : comme ça, même si un .git est supprimé ici,
# l'historique reste intact.
#
# Usage, depuis la racine du projet Prépa :
#     classes-prepa/publish.sh ["message de commit"]
set -e

PUBDIR="$(cd "$(dirname "$0")" && pwd)"      # …/Prépa/classes-prepa
GITDIR=/tmp/classes-prepa-git

# Initialisation du dépôt externe (une seule fois)
if [ ! -d "$GITDIR/.git" ]; then
  mkdir -p "$GITDIR"
  cd "$GITDIR"
  git init -b main >/dev/null
  git config core.worktree "$PUBDIR"
  git config user.name "francoismora"
  git config user.email "francoismora@users.noreply.github.com"
  git remote add origin https://github.com/francoismora/classes-prepa.git
  git fetch origin
  git update-ref refs/heads/main FETCH_HEAD
fi

export GIT_DIR="$GITDIR/.git"
export GIT_WORK_TREE="$PUBDIR"
cd "$PUBDIR"

# Synchronise les sources du site (docs/) vers ce sous-répertoire
rsync -a --delete --exclude 'publish.sh' ../docs/ ./

git add -A
if git diff --cached --quiet; then
  echo "Aucun changement à publier."
  exit 0
fi

git commit -m "${1:-Mise à jour du site}

Generated by Mistral Vibe.
Co-Authored-By: Mistral Vibe <vibe@mistral.ai>"

git push origin main
echo "Publié sur github.com/francoismora/classes-prepa (branche main)."
echo "Site : https://francoismora.github.io/classes-prepa/ (build GitHub Pages déclenché)."
